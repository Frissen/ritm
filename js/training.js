  function toggleLesson(host, pid, lid) {
    const d = data();
    const k = lessonKey(pid, lid);
    const p = PROG_BY_ID[pid];
    const lesson = p && p.lessons.find((x) => x.id === lid);
    if (d.lessons[k]) {
      delete d.lessons[k];
    } else {
      d.lessons[k] = new Date().toISOString();
      d.sessions.unshift({
        id: RU.uid(), at: new Date().toISOString(),
        title: p.title + ': ' + lesson.title, minutes: lesson.minutes || 0
      });
      if (d.sessions.length > 200) d.sessions.length = 200;
      UI.confetti(22);
      UI.beep();
      UI.toast({ icon: '✅', title: 'Занятие отмечено', text: lesson.title, kind: 'ok' });
    }
    Store.save(true);
    paint(host);
  }

  function openLesson(host, pid, lid) {
    const p = PROG_BY_ID[pid];
    const l = p.lessons.find((x) => x.id === lid);
    const done = !!data().lessons[lessonKey(pid, lid)];
    const body =
      '<div class="tr-material">' +
        '<p class="tr-material__sum">' + RU.escapeHtml(l.summary) + '</p>' +
        '<h4>Как выполнять</h4>' +
        '<ol class="tr-material__steps">' + l.steps.map((s) =>
          '<li>' + RU.escapeHtml(s) + '</li>').join('') + '</ol>' +
        '<p class="tr-muted">⏱ Рекомендуемое время: ' + l.minutes + ' мин</p>' +
      '</div>';
    UI.openModal({
      title: l.title, body: body, noFocus: true,
      foot: '<button class="btn btn--ghost" data-close="modal">Закрыть</button>' +
        '<button class="btn btn--accent" id="trMark">' + (done ? 'Снять отметку' : 'Отметить выполнено') + '</button>',
      onMount: (b, f) => {
        const btn = f.querySelector('#trMark');
        if (btn) btn.addEventListener('click', () => {
          UI.closeModal();
          toggleLesson(host, pid, lid);
        });
      }
    });
  }

  function openPlanForm(host) {
    let items = [];
    const body =
      '<form id="planForm" class="form" novalidate>' +
        '<label class="field"><span class="field__label">Название плана *</span>' +
          '<input class="field__input" name="name" maxlength="60" placeholder="Например, подготовка к забегу" required></label>' +
        '<label class="field"><span class="field__label">Цель</span>' +
          '<input class="field__input" name="goal" maxlength="120" placeholder="Например, 3 тренировки в неделю"></label>' +
        '<div class="field"><span class="field__label">Пункты плана</span>' +
          '<div class="tr-edit" id="planItems"></div>' +
          '<div class="tr-edit__add">' +
            '<input class="field__input" id="planItemInput" maxlength="80" placeholder="Добавить пункт и нажмите «+»">' +
            '<input class="field__input tr-edit__min" id="planItemMin" type="number" min="0" max="600" placeholder="мин">' +
            '<button type="button" class="btn btn--sm" id="planItemAdd">+</button>' +
          '</div>' +
        '</div>' +
      '</form>';
    UI.openModal({
      title: 'Новый план', body: body, noFocus: true,
      foot: '<button class="btn btn--ghost" data-close="modal">Отмена</button>' +
        '<button class="btn btn--accent" id="planSave">Создать план</button>',
      onMount: (b, f) => {
        const list = b.querySelector('#planItems');
        const input = b.querySelector('#planItemInput');
        const minInput = b.querySelector('#planItemMin');
        const drawItems = () => {
          list.innerHTML = items.length ? items.map((it, i) =>
            '<span class="tr-edit__chip">' + RU.escapeHtml(it.title) +
            (it.minutes ? ' · ' + it.minutes + ' мин' : '') +
            '<button type="button" data-rm="' + i + '" aria-label="Удалить">×</button></span>').join('')
            : '<span class="tr-muted">Пунктов пока нет — добавьте хотя бы один.</span>';
        };
        const addItem = () => {
          const title = input.value.trim();
          if (!title) return;
          items.push({ id: RU.uid(), title: title, minutes: +minInput.value || 0, done: false });
          input.value = ''; minInput.value = ''; input.focus();
          drawItems();
        };
        b.querySelector('#planItemAdd').addEventListener('click', addItem);
        input.addEventListener('keydown', (e) => {
          if (e.key === 'Enter') { e.preventDefault(); addItem(); }
        });
        list.addEventListener('click', (e) => {
          const rm = e.target.closest('[data-rm]');
          if (rm) { items.splice(+rm.getAttribute('data-rm'), 1); drawItems(); }
        });
        drawItems();
        f.querySelector('#planSave').addEventListener('click', () => {
          const form = b.querySelector('#planForm');
          const q = (n) => form.querySelector('[name="' + n + '"]');
          const nameEl = q('name');
          const name = nameEl.value.trim();
          if (!name) { nameEl.focus(); return; }
          if (!items.length) { input.focus(); return; }
          data().plans.unshift({
            id: RU.uid(), name: name, goal: q('goal').value.trim(),
            createdAt: new Date().toISOString(), items: items
          });
          Store.save(true);
          UI.closeModal();
          ts.view = 'plans'; ts.openPlan = data().plans[0].id;
          UI.confetti(26);
          UI.toast({ icon: '🗂', title: 'План создан', text: name, kind: 'ok' });
          paint(host);
        });
      }
    });
  }

