  function bind(host) {
    host.querySelector('.tr-tabs').addEventListener('click', (e) => {
      const b = e.target.closest('[data-view]');
      if (!b) return;
      ts.view = b.getAttribute('data-view');
      ts.openProgram = null;
      paint(host);
    });

    host.querySelector('#trBody').addEventListener('click', (e) => {
      const el = e.target.closest('[data-tr]');
      if (!el) return;
      const act = el.getAttribute('data-tr');
      const pid = el.getAttribute('data-p');
      const lid = el.getAttribute('data-l');
      const id = el.getAttribute('data-id');

      if (act === 'open-program') { ts.openProgram = id; paint(host); }
      else if (act === 'back') { ts.openProgram = null; paint(host); }
      else if (act === 'filter') {
        const kind = el.getAttribute('data-kind');
        const val = el.getAttribute('data-val');
        if (kind === 'level') ts.fLevel = val;
        else if (kind === 'goal') ts.fGoal = val;
        paint(host);
      }
      else if (act === 'toggle-lesson') toggleLesson(host, pid, lid);
      else if (act === 'lesson') openLesson(host, pid, lid);
      else if (act === 'new-plan') openPlanForm(host);
      else if (act === 'toggle-plan') { ts.openPlan = ts.openPlan === id ? null : id; paint(host); }
      else if (act === 'toggle-item') {
        const plan = data().plans.find((p) => p.id === id);
        const item = plan && plan.items.find((i) => i.id === el.getAttribute('data-i'));
        if (item) {
          item.done = !item.done;
          if (item.done) { UI.confetti(14); UI.beep(); }
          Store.save(true);
          paint(host);
        }
      }
      else if (act === 'del-plan') {
        confirmDelete('Удалить план без возможности восстановления?', () => {
          const d = data();
          d.plans = d.plans.filter((p) => p.id !== id);
          Store.save(true);
          UI.toast({ icon: '🗑', title: 'План удалён' });
          paint(host);
        });
      }
      else if (act === 'new-session') openSessionForm(host);
      else if (act === 'del-session') {
        const d = data();
        d.sessions = d.sessions.filter((s) => s.id !== id);
        Store.save(true);
        paint(host);
      }
    });

    host.querySelector('#trBody').addEventListener('keydown', (e) => {
      if (e.key !== 'Enter') return;
      const card = e.target.closest('[data-tr="open-program"]');
      if (card) { ts.openProgram = card.getAttribute('data-id'); paint(host); }
    });
  }

